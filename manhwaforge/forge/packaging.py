def write_reader(out_dir: Path, script: Script, layout: Layout, title: str) -> Path:
    """Self-contained reader (open reader/index.html straight from the unzipped package)."""
    rd = out_dir / "reader"
    img_dir = rd / "img"
    img_dir.mkdir(parents=True, exist_ok=True)
    t = html.escape(title)
    if layout.format == "slides":
        names = []
        for i, sp in enumerate(layout.slide_paths):
            dst = img_dir / f"slide_{i + 1:02d}.jpg"
            dst.write_bytes((out_dir / sp).read_bytes())
            names.append(f"img/{dst.name}")
        body = f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{t}</title><style>{_SLIDES_CSS}</style></head><body>
<div id="stage"><img id="s" alt="slide"></div>
<nav><button id="p">&larr; Prev</button><span id="c"></span><button id="n">Next &rarr;</button><button id="f">Fullscreen</button></nav>
<script>
const slides={json.dumps(names)};let i=0;const s=document.getElementById('s'),c=document.getElementById('c');
function show(k){{i=Math.max(0,Math.min(slides.length-1,k));s.src=slides[i];c.textContent=(i+1)+' / '+slides.length;}}
document.getElementById('p').onclick=()=>show(i-1);document.getElementById('n').onclick=()=>show(i+1);
document.getElementById('stage').onclick=()=>show(i+1);
document.getElementById('f').onclick=()=>document.documentElement.requestFullscreen&&document.documentElement.requestFullscreen();
addEventListener('keydown',e=>{{if(['ArrowRight',' ','PageDown'].includes(e.key))show(i+1);if(['ArrowLeft','PageUp'].includes(e.key))show(i-1);}});show(0);
</script></body></html>"""
    else:
        figs = []
        entries = layout.to_json()["panels"]
        for n, e in enumerate(entries):
            idx, gut, inset = e["index"], e["gutter_after"], e["inset"]
            src = out_dir / "panels" / f"panel_{idx + 1:02d}.png"
            right = inset and e["x"] > 0
            dst = img_dir / f"panel_{idx + 1:02d}.jpg"
            Image.open(src).convert("RGB").save(dst, quality=90, optimize=True)
            cls = ("inset" + (" r" if right else "")) if inset else ""
            g = f"margin-bottom:min({gut / layout.width * 100:.2f}vw,{gut}px)" if n < len(entries) - 1 else ""
            figs.append(f'<figure class="{cls}" style="{g}"><img loading="lazy" src="img/{dst.name}" alt="Panel {idx + 1}"></figure>')
        body = f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{t}</title><style>{_READER_CSS}</style></head><body><div id="bar"></div>
<header><h1>{t}</h1><p class="sub">{len(layout.entries)} panels &middot; scroll to read</p></header>
<main>{''.join(figs)}</main>
<div class="end"><b>End of chapter</b>Generated by ManhwaForge Studio</div>
<script>addEventListener('scroll',()=>{{const h=document.documentElement;document.getElementById('bar').style.width=(h.scrollTop/(h.scrollHeight-h.clientHeight||1)*100)+'%'}});</script>
</body></html>"""
    path = rd / "index.html"
    path.write_text(body, encoding="utf-8")
    return path


def write_summary(out_dir: Path, state: JobState, script: Script, layout: Layout, events_tail: list[dict],
                  halted: Optional[dict], finalized: bool, extra_notes: Optional[list[str]] = None) -> None:
    """Completion summary log (markdown + json). Written at the 95% hard save and rewritten after a manual finalize."""
    scores = [p.score for p in state.panels if p.score is not None]
    weak = [p for p in state.panels if p.below_threshold]
    summary = {
        "title": state.title,
        "job_id": state.id,
        "format": state.format,
        "generated_at": time.strftime("%Y-%m-%d %H:%M:%S UTC", time.gmtime()),
        "status": "completed" if finalized else "halted at completion threshold (awaiting manual instruction)",
        "progress_percent": round(state.progress * 100, 2),
        "confidence_percent": round(state.confidence * 100, 2),
        "halt": halted,
        "style": state.style.model_dump() if state.style else None,
        "director": state.director_source,
        "characters": state.characters,
        "panel_count": len(state.panels),
        "amazement": {
            "threshold": 7.5,
            "mean": round(sum(scores) / len(scores), 2) if scores else None,
            "min": min(scores) if scores else None,
            "max": max(scores) if scores else None,
            "below_threshold_panels": [p.index + 1 for p in weak],
        },
        "stage_progress": state.stage_progress,
        "pending": [] if finalized else ["final polish (5%): output optimisation and credits - run via 'resume' / 'finalize'"],
        "panels": [p.model_dump() for p in state.panels],
        "notes": extra_notes or [],
    }
    (out_dir / "completion_summary.json").write_text(json.dumps(summary, indent=2, default=str), encoding="utf-8")

    L: list[str] = [f"# Completion summary: {state.title}", ""]
    L.append(f"- **Status:** {summary['status']}")
    L.append(f"- **Progress / confidence:** {summary['progress_percent']}% / {summary['confidence_percent']}%")
    if halted:
        L.append(f"- **Halt trigger:** {halted.get('reason')}")
    L.append(f"- **Format:** {state.format} · **Panels:** {len(state.panels)} · **Script by:** {state.director_source}")
    if state.style:
        L.append(f"- **Style:** {state.style.name} ({'; '.join(state.style.reasons)})")
    L.append(f"- **Characters:** {', '.join(state.characters) or 'none'}")
    am = summary["amazement"]
    L.append(f"- **Amazement score:** mean {am['mean']} (min {am['min']}, max {am['max']}), gate {am['threshold']}")
    if weak:
        L.append(f"- **Below the gate after the retry cap:** panels {', '.join(str(p.index + 1) for p in weak)} (shipped at best score, flagged)")
    else:
        L.append("- **Every panel cleared the Amazement gate.**")
    if not finalized:
        L.append("")
        L.append("## Halted: awaiting manual instruction")
        L.append("The 95% rule fired and execution stopped. Nothing further runs until you issue an instruction "
                 "(`POST /api/jobs/<id>/resume`, or the *Finalize* button in the dashboard). Pending: final polish (the last 5%).")
    L += ["", "## Panels", "", "| # | shot | attempts | score | anatomy | lighting | lines | gate |", "|---|------|----------|-------|---------|----------|-------|------|"]
    for p in state.panels:
        L.append(f"| {p.index + 1} | {p.shot} | {p.attempts} | {p.score} | {p.anatomy if p.anatomy is not None else '-'} | {p.lighting} | {p.lines} | "
                 f"{'FLAGGED' if p.below_threshold else 'pass'} |")
    if state.panels:
        L += ["", "Score history per panel (each retry the Artist made):", ""]
        for p in state.panels:
            if len(p.history) > 1:
                L.append(f"- panel {p.index + 1}: " + " → ".join(f"{h:.2f}" for h in p.history))
    if extra_notes:
        L += ["", "## Notes", ""] + [f"- {n}" for n in extra_notes]
    L += ["", "## Log tail", "", "```"] + [f"[{e['agent']}] {e['msg']}" for e in events_tail[-25:]] + ["```", ""]
    (out_dir / "completion_summary.md").write_text("\n".join(L), encoding="utf-8")


def make_zip(job_dir: Path, out_dir: Path, name: str) -> Path:
    """Package output/ into <job>/<name>.zip. Written to a temp file then renamed, so a download never sees a partial zip."""
    for old in job_dir.glob("*.zip"):
        old.unlink()
    target = job_dir / f"{name}.zip"
    tmp = job_dir / f".{name}.zip.tmp"
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for p in sorted(out_dir.rglob("*")):
            if p.is_file():
                z.write(p, p.relative_to(out_dir).as_posix())
    tmp.replace(target)
    return target
