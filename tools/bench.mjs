// Reproducible simulation benchmark. Usage: node tools/bench.mjs [months=24] [outfile]
// Reports wall-clock numbers for THIS machine/Node build only; they are not device (iPhone) numbers.
import fs from 'node:fs';
import os from 'node:os';
import { loadDataNode } from '../app/js/sim/data.js';
import { Sim } from '../app/js/sim/world.js';
import { serialize, deserialize } from '../app/js/sim/save.js';

const months = +process.argv[2] || 24, outFile = process.argv[3];
const now = () => performance.now();
const pct = (a, p) => { const s = [...a].sort((x, y) => x - y); return s[Math.min(s.length - 1, Math.floor(p * s.length))]; };
const rows = [];
let t = now(); const data = await loadDataNode(); const tData = now() - t;
t = now(); const sim = new Sim(data, { seed: 42, scenario: 'fault_lines', player: 'DEU' }); const tInit = now() - t;
// chunk slices: what the UI frame loop sees (stepGen yields between phases)
const slices = []; const monthMs = [];
const end = sim.state.day + months * 30;
let last = now(), monthStart = last, lastMonth = sim.state.day;
while (sim.state.day < end) {
  const g = sim.stepGen(); let r;
  while (!(r = g.next()).done) { const n = now(); slices.push(n - last); last = n; }
  const n = now(); slices.push(n - last); last = n;
}
const total = last - monthStart;
const heap = process.memoryUsage().heapUsed / 1e6;
t = now(); const txt = serialize(sim); const tSer = now() - t;
t = now(); deserialize(data, txt); const tLoad = now() - t;
const dayMs = slices; // per-yield slices include daily steps
const out = {
  machine: `${os.cpus()[0]?.model ?? 'cpu'} x${os.cpus().length}, Node ${process.version}`,
  scenario: 'fault_lines seed 42', simulatedMonths: months,
  dataLoadMs: +tData.toFixed(0), newGameMs: +tInit.toFixed(0),
  msPerSimulatedMonth: +(total / months).toFixed(1),
  slicesMs: { count: dayMs.length, median: +pct(dayMs, 0.5).toFixed(2), p95: +pct(dayMs, 0.95).toFixed(2), p99: +pct(dayMs, 0.99).toFixed(2), max: +Math.max(...dayMs).toFixed(1) },
  saveMB: +(txt.length / 1e6).toFixed(2), serializeMs: +tSer.toFixed(0), deserializeMs: +tLoad.toFixed(0), heapMB: +heap.toFixed(0),
};
console.log(JSON.stringify(out, null, 2));
if (outFile) {
  fs.writeFileSync(outFile, `# Benchmark (Node, desktop-class machine)\n\nGenerated by \`tools/bench.mjs ${months}\`. Numbers describe this machine only and are **not** iPhone measurements.\n\n\`\`\`json\n${JSON.stringify(out, null, 2)}\n\`\`\`\n`);
}
