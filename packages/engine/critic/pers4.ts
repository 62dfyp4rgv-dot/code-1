import { createWorld, advanceDays } from '../src/world/sim';
import { defaultWorldConfig } from '../src/world/generate';
import { encodeWorld, checksumOf } from '../src/persistence/codec';
import { SaveRepository } from '../src/persistence/repository';
import { NodeSqliteDriver } from '../src/persistence/nodeSqliteDriver';
import { overall } from '../src/players';
import { validateWorld } from '../src/world/invariants';
const cfg = defaultWorldConfig('critic-p', 'compact');
const w = createWorld(cfg);
const ch = encodeWorld(w).map((c) => ({ ...c }));
const pc = ch.find((c) => c.kind === 'players')!;
const arr = JSON.parse(pc.data); const victim = arr[0].id; arr[0].attrs = arr[0].attrs.slice(0, 5); pc.data = JSON.stringify(arr);
const doc = JSON.stringify({ format: 'football-universe-save', version: 1, checksum: checksumOf(ch), chunks: ch });
const repo = new SaveRepository(new NodeSqliteDriver()); await repo.init();
await repo.importSlot(1, 'hostile', doc);
const { world: lw } = await repo.load(1);
console.log('[truncated attrs] import accepted; validateWorld violations:', validateWorld(lw).filter((v) => v.code === 'ATTR_RANGE').length);
const nonFinite = () => Object.values(lw.players).filter((p) => !Number.isFinite(overall(p))).map((p) => p.id);
console.log('[truncated attrs] players with non-finite overall at import:', nonFinite().length, nonFinite().slice(0, 3));
advanceDays(lw, 60);
console.log('[truncated attrs] after 60 simulated days (no exception): non-finite overall players', nonFinite().length, '; club of victim cash finite:', Number.isFinite(lw.clubs[lw.players[victim]!.clubId!]!.finance.cash));
const nanStats = Object.values(lw.seasonStats).flatMap((m) => Object.values(m)).filter((s) => !Number.isFinite(s.ratingSum)).length;
console.log('[truncated attrs] stat lines with NaN rating:', nanStats);
const vp = lw.players[victim]!;
console.log('[debug] victim', victim, vp.primary, 'attrs sample', JSON.stringify(vp.attrs).slice(0, 160), 'overall', overall(vp));
